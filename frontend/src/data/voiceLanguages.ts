export const VOICE_LANGUAGES: VoiceLanguage[] = APP_LANGUAGES.map((language) => ({
  code: language.code,
  englishName: language.englishName,
  nativeName: language.nativeName,
  locale: LOCALES[language.code],
  geminiTts: GEMINI_TTS_LANGUAGES.has(language.code)
}));

